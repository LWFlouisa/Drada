/* ######################################################################################### */
/* #                                       Word Order                                      # */
/* ######################################################################################### */
void osv(char o[], char s[], char v[]) {
  printf("%s %s %s, ", o, s, v);
}

void sov(char s[], char o[], char v[]) {
  printf("%s %s %s.\n", s, o, v);
}

void vos(char v[], char o[], char s[]) {
  printf("%s %s %s.\n", v, o, s);
}

